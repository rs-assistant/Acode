import { rspack } from "@rspack/core";
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const root = fileURLToPath(new URL("../../", import.meta.url));
const cookiePackage = JSON.parse(
	await readFile(require.resolve("tough-cookie/package.json"), "utf8"),
);
if (cookiePackage.version !== "4.1.4")
	throw new Error(
		"Review the cookie migration before changing its pinned version",
	);

const output = path.join(root, "src/plugins/cordova-plugin-advanced-http/www");
// Include the complete upstream notices for every third-party package included
// by this browser bundle, not just the top-level cookie parser.
const licenses = [];
const cookieRequire = createRequire(require.resolve("tough-cookie"));
const urlRequire = createRequire(cookieRequire.resolve("url-parse"));
for (const name of [
	"tough-cookie",
	"psl",
	"punycode",
	"universalify",
	"url-parse",
	"querystringify",
	"requires-port",
]) {
	const resolver = ["querystringify", "requires-port"].includes(name)
		? urlRequire
		: cookieRequire;
	let directory = path.dirname(
		resolver.resolve(name === "punycode" ? "punycode/" : name),
	);
	let pkg;
	// Some packages intentionally do not export package.json; find it from the
	// actual resolved entry instead of assuming node_modules layout/hoisting.
	while (directory !== path.dirname(directory)) {
		try {
			const candidate = JSON.parse(
				await readFile(path.join(directory, "package.json"), "utf8"),
			);
			if (candidate.name === name) {
				pkg = candidate;
				break;
			}
		} catch {}
		directory = path.dirname(directory);
	}
	if (!pkg) throw new Error(`Missing package metadata for ${name}`);
	let license;
	for (const filename of ["LICENSE", "LICENSE.txt", "LICENSE-MIT.txt"]) {
		try {
			license = await readFile(path.join(directory, filename), "utf8");
			break;
		} catch {}
	}
	if (!license) throw new Error(`Missing license for ${name}`);
	licenses.push(`${name} ${pkg.version}\n${license.trim()}`);
}
const compiler = rspack({
	mode: "production",
	target: ["web", "es2015"],
	entry: require.resolve("tough-cookie"),
	devtool: false,
	output: {
		path: output,
		filename: "umd-tough-cookie.js",
		library: { type: "commonjs2" },
		clean: false,
	},
	plugins: [
		new rspack.NormalModuleReplacementPlugin(
			/utilHelper(?:\.js)?$/,
			path.join(root, "utils/security/cookie-browser-util.cjs"),
		),
		new rspack.BannerPlugin({
			banner:
				"tough-cookie 4.1.4 and locked browser dependencies; licenses: tough-cookie.LICENSE.\nGenerated by npm run build:http-cookie; do not edit this distribution manually.",
		}),
	],
});
await new Promise((resolve, reject) =>
	compiler.run((error, stats) => {
		compiler.close((closeError) => {
			if (error || closeError) reject(error || closeError);
			else if (stats.hasErrors())
				reject(new Error(stats.toString({ all: false, errors: true })));
			else resolve();
		});
	}),
);
await writeFile(
	path.join(output, "tough-cookie.LICENSE"),
	licenses.join("\n\n---\n\n") + "\n",
);
console.log(
	"Built pinned browser cookie distribution and complete dependency licenses.",
);
